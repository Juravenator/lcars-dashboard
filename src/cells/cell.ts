export abstract class Cell {
    x: number;
    y: number;
    w: number;
    h: number;

    constructor(x: number, y: number, w: number, h: number) {
        this.x = x;
        this.y = y;
        this.w = w;
        this.h = h;
    }

    abstract frame(): void;
    abstract click(x: number, y: number): boolean;
}